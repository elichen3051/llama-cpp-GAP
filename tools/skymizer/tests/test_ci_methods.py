@pytest.mark.parametrize("weighting", ["item"])
def test_t_interval_is_the_textbook_paired_t(weighting):
    """theta -+ t_{n-1, 0.975} * SE with the SAME SE the studentized method
    uses (s/sqrt(n) item-weighted),
    and p = P(|T_{n-1}| >= |theta/SE|). scipy is the oracle when present;
    the closed form below is checked regardless."""
    d = _skewed(37, 0.9, 4)
    w = np.arange(1, 38, dtype=float) * 3.0
    base = np.zeros_like(d)
    res = _paired_bootstrap_delta(base, d, w, weighting=weighting,
                                     confidence_level=0.95,
                                     bootstrap_iters=0, seed=None,
                                     ci_method="t")
    theta, se = _statistic_and_se(d, w, weighting)
    q = t_ppf(0.975, 36)
    assert res["estimate"] == theta
    assert res["ci"]["lower"] == pytest.approx(theta - q * se, rel=1e-14)
    assert res["ci"]["upper"] == pytest.approx(theta + q * se, rel=1e-14)
    assert res["ci"]["standard_error"] == se
    assert res["ci"]["degrees_of_freedom"] == 36
    assert res["ci"]["bootstrap_iters"] == 0
    assert res["ci"]["ci_method"] == "t"
    assert res["ci"]["method"] == f"paired_{weighting}_weighted_student_t"
    assert res["bootstrap_std"] is None
    assert "fallback" not in res["ci"]
    assert res["p_value"] == pytest.approx(t_two_sided_p(theta / se, 36), rel=1e-14)
    st = pytest.importorskip("scipy.stats")
    assert q == pytest.approx(st.t.ppf(0.975, 36), rel=1e-10)
    if weighting == "item":
        # the item-weighted case IS scipy's paired t-test
        tt = st.ttest_rel(d, base)
        assert res["p_value"] == pytest.approx(float(tt.pvalue), rel=1e-9)
        lo, hi = tt.confidence_interval(0.95)
        assert res["ci"]["lower"] == pytest.approx(float(lo), rel=1e-9)
        assert res["ci"]["upper"] == pytest.approx(float(hi), rel=1e-9)


def test_t_interval_ignores_seed_and_iters():
    """No replicate is drawn: the result is a pure function of the deltas."""
    d = _skewed(30, 1.0, 7)
    base, w = np.zeros_like(d), np.ones_like(d)
    a = _paired_bootstrap_delta(base, d, w, weighting="item",
                                   confidence_level=0.95, bootstrap_iters=5000,
                                   seed=1, ci_method="t")
    b = _paired_bootstrap_delta(base, d, w, weighting="item",
                                   confidence_level=0.95, bootstrap_iters=0,
                                   seed=99, ci_method="t")
    assert a == b
    assert min_bootstrap_iters(0.95, "t") == 0
    assert min_bootstrap_iters(0.99, "t") == 0


def test_t_interval_is_a_point_on_a_degenerate_sample():
    """Identical deltas (SE = 0): the interval is [theta, theta] and p is the
    SE -> 0 limit of the t test -- 0 when theta != 0, 1 when theta == 0 --
    with the JSON saying why, mirroring the bootstrap methods' zero-spread
    fallback note."""
    d = np.full(12, -0.75)
    base, w = np.zeros_like(d), np.ones_like(d)
    res = _paired_bootstrap_delta(base, d, w, weighting="item",
                                     confidence_level=0.95, bootstrap_iters=0,
                                     seed=None, ci_method="t")
    assert res["ci"]["lower"] == res["ci"]["upper"] == -0.75
    assert res["p_value"] == 0.0
    assert "no spread" in res["ci"]["fallback"]
    assert res["ci"]["ci_method"] == "t"
    zero = _paired_bootstrap_delta(base, np.zeros(12), w, weighting="item",
                                      confidence_level=0.95, bootstrap_iters=0,
                                      seed=None, ci_method="t")
    assert zero["p_value"] == 1.0 and zero["ci"]["contains_zero"]
    with pytest.raises(ValueError, match="at least two"):
        _paired_bootstrap_delta(np.zeros(1), np.ones(1), np.ones(1),
                                weighting="item", confidence_level=0.95,
                                bootstrap_iters=0, seed=None, ci_method="t")


def test_t_interval_plumbs_through_compare_items():
    scores_a = [{"kld": 0.10 + 0.01 * i} for i in range(9)]
    scores_b = [{"kld": 0.11 + 0.02 * i} for i in range(9)]
    w = [10] * 9
    res = compare_items(scores_a, scores_b, w, metrics=["kld"],
                           confidence_level=0.95, bootstrap_iters=1000, seed=1,
                           model_a_label="A", model_b_label="B", ci_method="t")
    assert res["ci_method"] == "t"
    assert res["bootstrap_iters"] == 0
    for weighting in ("item_weighted",):
        cell = res["metrics"]["kld"][weighting]
        assert cell["ci_delta"]["ci_method"] == "t"
        assert cell["ci_delta"]["degrees_of_freedom"] == 8
        assert cell["bootstrap_std"] is None
    md = format_comparison_table(res, reference_label="F16")
    assert "95% CI via paired Student-t (df = n - 1, no bootstrap)" in md
    assert "paired-bootstrap iters" not in md


