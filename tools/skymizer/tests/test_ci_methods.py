@pytest.mark.parametrize("weighting", ["item"])
def test_statistic_and_se_matches_a_direct_computation(weighting):
    """The independent units determine the unweighted mean's standard error."""
    d = np.array([-2., -1., 0., 1., 2.])
    w = np.array([1., 2., 3., 4., 1000.])
    theta, se = _statistic_and_se(d, w, weighting)
    assert theta == 0.0
    assert se == pytest.approx(math.sqrt(0.5))


def test_studentized_interval_is_the_crossed_bootstrap_t_form():
    """[theta - t_(1-a/2) SE, theta - t_(a/2) SE] -- writing the quantiles the
    obvious way round silently yields a percentile-like interval reflected
    through the estimate, which passes most smoke tests."""
    d = _skewed(45, 0.9, 33)
    base, w = np.zeros_like(d), np.ones_like(d)
    res = _paired_bootstrap_delta(base, d, w, weighting="item",
                                     confidence_level=0.95,
                                     bootstrap_iters=3000, seed=8,
                                     ci_method="studentized")
    theta, se = _statistic_and_se(d, w, "item")
    t_star = []
    for idx in _bootstrap_item_indices(8, d.size, 3000):
        th, s = _statistic_and_se(d[idx], w[idx], "item")
        if s > 0:
            t_star.append((th - theta) / s)
    t_star = np.asarray(t_star)
    t_hi, t_lo = np.quantile(t_star, [0.975, 0.025])
    assert res["ci"]["lower"] == pytest.approx(theta - t_hi * se, rel=1e-12)
    assert res["ci"]["upper"] == pytest.approx(theta - t_lo * se, rel=1e-12)
    assert res["ci"]["standard_error"] == pytest.approx(se)


def test_studentized_falls_back_when_there_is_no_spread():
    d = np.full(12, -0.75)
    base, w = np.zeros_like(d), np.ones_like(d)
    res = _paired_bootstrap_delta(base, d, w, weighting="item",
                                     confidence_level=0.95,
                                     bootstrap_iters=1000, seed=1,
                                     ci_method="studentized")
    assert res["ci"]["ci_method"] == "percentile"
    assert "no spread" in res["ci"]["fallback"]


